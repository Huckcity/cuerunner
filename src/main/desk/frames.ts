export interface FrameReader {
  /** Whatever came off the socket, and the frames that are now whole. */
  push(chunk: ArrayLike<number>): number[][]
}

/**
 * Splits what a socket delivers into frames.
 *
 * One read is not one frame. The capture's own layout push arrives in a chunk that declares
 * 8192 bytes and carries more after them; a frame can be split across two reads; and the
 * desk's pushes share reads with whatever follows. So the reader holds what it cannot finish,
 * steps over bytes that cannot open a frame, and hands out whole frames as they complete.
 */
export function createFrameReader(): FrameReader {
  let pending = new Uint8Array(0)

  return {
    push(chunk) {
      const frames: number[][] = []
      if (chunk.length > 0) {
        const joined = new Uint8Array(pending.length + chunk.length)
        joined.set(pending)
        joined.set(chunk, pending.length)
        pending = joined
      }

      for (;;) {
        if (pending.length === 0) break
        const head = pending[0]

        if (head !== FAMILY_7F && head !== FAMILY_F7) {
          // Neither family opens here. The bytes are the tail of something whose length did
          // not account for them — the capture's push chunk carries a run of them — so they
          // are stepped over to the next byte that could open a frame, and dropped when
          // there is none.
          const next = nextStart(pending)
          if (next === -1) {
            pending = new Uint8Array(0)
            break
          }
          pending = pending.subarray(next)
          continue
        }

        if (head === FAMILY_F7) {
          if (pending.length < F7_FRAME_BYTES) break
          frames.push(Array.from(pending.subarray(0, F7_FRAME_BYTES)))
          pending = pending.subarray(F7_FRAME_BYTES)
          continue
        }

        if (pending.length < HEADER_BYTES) break
        const length = (pending[2] | (pending[3] << 8) | (pending[4] << 16) | (pending[5] << 24)) >>> 0
        if (length > MAX_PAYLOAD_BYTES) {
          // Not a header, whatever it looks like: a payload byte the stream is reading as
          // one. Looking past it is how the reader recovers a frame inside a run of bytes
          // nobody accounted for.
          pending = pending.subarray(1)
          continue
        }
        const total = HEADER_BYTES + length
        if (pending.length < total) break
        frames.push(Array.from(pending.subarray(0, total)))
        pending = pending.subarray(total)
      }

      return frames
    }
  }
}

/** The first byte past the one already known not to open a frame, or -1 when there is none. */
function nextStart(bytes: Uint8Array): number {
  for (let i = 1; i < bytes.length; i++) {
    if (bytes[i] === FAMILY_7F || bytes[i] === FAMILY_F7) return i
  }
  return -1
}
