/**
 * The SQ's own control service — the desk's native protocol on TCP 51326, which Allen &
 * Heath publish nothing about — as the bytes were measured from an SQ-6 running firmware
 * 1.6.1 on 2026-09-22.
 *
 * The capture is `integration/fixtures/vendor/sq6-native-apply-2026-09-22.json` and it is
 * the contract for every byte here: the codec's own cases are driven from it rather than
 * from prose, and where a sentence elsewhere disagrees with it the fixture is what the desk
 * reads. Nothing here invents a frame the capture did not measure.
 *
 * Two families share the one socket. The first is `7f <command> <length: 4 bytes
 * little-endian> <payload>`; the second is a family of eight-byte frames beginning `f7`,
 * which is what a DCA membership is written with — one frame per (channel, DCA) pair.
 */

/** The desk's own control service. Not a setting: it is the desk's, and `desk.tcpPort`
 *  keeps meaning the MIDI service's port on 51325. */
export const NATIVE_TCP_PORT = 51326

/** Where the session's keepalive datagram goes, once a second, on the desk's address. */
export const NATIVE_KEEPALIVE_PORT = 51324

/** The range's own leave port: what a client says `BYE.` on before it lets the desk go. */
export const NATIVE_LEAVE_PORT = 51321

/** The first family's leading byte. */
const FAMILY_7F = 0x7f

/** The second family's leading byte, and its width: eight bytes, every frame of it. */
const FAMILY_F7 = 0xf7
const F7_FRAME_BYTES = 8
const F7_PAYLOAD_BYTES = F7_FRAME_BYTES - 2

/** The first family's header: the leading byte, the command, and the payload's length. */
const HEADER_BYTES = 6

/**
 * The longest payload that is a frame. The capture's layout push declares 8192 bytes; past
 * this the stream has lost its place rather than found a long message, and the reader says
 * so by looking for the next byte that could open a frame — the judgement `stream.ts` makes
 * about a SysEx that never terminates.
 */
const MAX_PAYLOAD_BYTES = 64 * 1024

/** `BYE.`, in ASCII, on port 51321. A client that dies without it leaves a real SQ mute
 *  until somebody resets the desk (§6, measured). */
export const GOODBYE = [0x42, 0x59, 0x45, 0x2e]

/** The first family: a command and its payload, under the length the desk reads. */
function seven(command: number, payload: readonly number[]): number[] {
  const length = payload.length
  return [
    FAMILY_7F,
    command,
    length & 0xff,
    (length >>> 8) & 0xff,
    (length >>> 16) & 0xff,
    (length >>> 24) & 0xff,
    ...payload
  ]
}

/**
 * The second family: always eight bytes, `f7 <command>` and six bytes after it. A frame of
 * another width is not one this protocol reads, so a payload of the wrong size is refused
 * here rather than written as a frame the desk would lose its place in.
 */
function eight(command: number, payload: readonly number[]): number[] {
  if (payload.length !== F7_PAYLOAD_BYTES) {
    throw new Error(`an \`f7\` frame carries six bytes after its command: ${payload.length} is not a frame`)
  }
  return [FAMILY_F7, command, ...payload]
}

/**
 * Placing one input on one DCA's fader, and taking it off: one frame per pair. The capture
 * holds the whole 16-input × 8-DCA matrix — 128 frames — of which exactly the four known
 * pairs are written `01 00` and the other 124 are cleared.
 */
export function assignPair(channel: number, dca: number): number[] {
  return eight(0x07, [0x07, 0x1d, channel - 1, dca - 1, 0x01, 0x00])
}

/** The same frame, clearing the pair. */
export function clearPair(channel: number, dca: number): number[] {
  return eight(0x07, [0x07, 0x1d, channel - 1, dca - 1, 0x00, 0x00])
}

/**
 * The per-channel "rides a DCA" flag, which follows the assignment.
 *
 * The capture's own pairing fixes which value names which state: the four channels its
 * `1d … 01 00` frames place carry `00 00 00` after the channel byte, and the twelve it
 * leaves alone carry `00 01 00`. So `00 00` is the channel that rides a DCA and `01` is the
 * channel that rides none — the polarity §6 and §11 decision 6 had printed the other way
 * round, corrected with this story.
 */
export function dcaFlag(channel: number, rides: boolean): number[] {
  return eight(0x07, [0x07, 0x0c, channel - 1, 0x00, rides ? 0x00 : 0x01, 0x00])
}

/**
 * The session's hello (`7f 00 02 …`), which is also the ping the socket is kept alive with
 * every three seconds: the capture holds one `7f 00 02` write, opens the session with it,
 * and this repeats it. Its two payload bytes are the capture's own; what the desk makes of
 * them is not measured, and a value invented here would be a frame nobody has seen.
 */
export function helloFrame(): number[] {
  return seven(0x00, [0x66, 0xae])
}

/**
 * The keepalive: eight bytes to UDP 51324 every second, `f7 05` and a zero payload. Its
 * cadence is §6's and its body is not — the eight-byte width is what the family measures,
 * and the record's claim stays unproven until a desk says otherwise (Story 11.5).
 */
export function keepAliveFrame(): number[] {
  return eight(0x05, [0x00, 0x00, 0x00, 0x00, 0x00, 0x00])
}

/**
 * The session, in the order the capture's wire shows it — which is not the order §6's prose
 * lists: `7f 0b 02` precedes the layout push on the wire, and a `7f 0d` frame follows it
 * that the prose never named. The wire is the contract, so the wire is what this writes.
 */
export function sessionFrames(): number[][] {
  return [
    helloFrame(),
    seven(0x01, []),
    seven(0x14, []),
    seven(0x0b, [0x02, 0x00]),
    seven(0x0a, LAYOUT_PUSH),
    seven(0x0d, []),
    seven(0x11, []),
    // `f7 02 02 20 ff ff ff ff`, the eight-byte frame the capture writes between `7f 11`
    // and `7f 03`.
    eight(0x02, [0x02, 0x20, 0xff, 0xff, 0xff, 0xff]),
    seven(0x03, [])
  ]
}

